// Current language: saved choice, or Arabic by default
let currentLang = store.get("lang") || "ar";

// Get one text in the current language
function t(key) {
  return TEXTS[currentLang][key] || key;
}

// Replace the text of every element that has data-i18n, and flip page direction
function applyLanguage() {
  document.documentElement.lang = currentLang;
  document.documentElement.dir = currentLang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  // The button shows the OTHER language (the one you can switch to)
  document.getElementById("langToggle").textContent = currentLang === "ar" ? "EN" : "عربي";
}

function toggleLanguage() {
  currentLang = currentLang === "ar" ? "en" : "ar";
  store.set("lang", currentLang);
  applyLanguage();
}
